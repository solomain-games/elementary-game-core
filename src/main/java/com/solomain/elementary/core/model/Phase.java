package com.solomain.elementary.core.model;

/**
 * Фаза партии.
 */
public enum Phase {
    /** Показ предыстории перед началом игры. */
    PROLOGUE,
    /** Игроки по очереди выкладывают и сбрасывают карты. */
    PLAYING,
    /** Колода, резерв и руки пусты; игроки обсуждают и могут начать голосование. */
    NO_MOVES_LEFT,
    /** Игроки отвечают на финальные вопросы. */
    ANSWERING,
    /** Партия завершена: показаны очки, истинная картина и сброс. */
    FINISHED
}

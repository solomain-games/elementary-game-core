package com.solomain.elementary.core.model;

/**
 * Карта дела.
 *
 * <p>Интерфейс запечатан ({@code sealed}): карт других типов не бывает,
 * поэтому {@code switch} по картам проверяется компилятором на полноту.
 * Реализации-records автоматически реализуют методы интерфейса своими полями.
 */
public sealed interface Card permits ImageCard, TextCard {
    /** Номер карты, начиная с 1. Карта №1 — стартовая, выкладывается на стол автоматически. */
    int number();

    /** Относится ли карта к делу; {@code false} — ложный след. Раскрывается только в финале. */
    boolean relevant();
}

package com.solomain.elementary.core.error;

/**
 * Нарушение правил игры.
 *
 * <p>Код передаётся клиенту, а текст для игрока берётся из переводов интерфейса по имени константы
 * (например, {@code errors.NOT_YOUR_TURN}). Поэтому в ядре нет текстов сообщений.
 */
public enum RuleViolation {
    /** Команда недопустима в текущей фазе партии (например, ход во время предыстории). */
    WRONG_PHASE,
    /** Игрока с таким идентификатором нет в партии. */
    UNKNOWN_PLAYER,
    /** Сейчас ход другого игрока. */
    NOT_YOUR_TURN,
    /** Такой карты нет в руке игрока. */
    CARD_NOT_IN_HAND,
    /** Команда не подходит к текущему статусу игрока (например, вернуться, не уходя). */
    INVALID_PLAYER_STATUS,
    /** В партии нет таймера хода, а пришёл сигнал о его истечении. */
    NO_TURN_TIMER,
    /** Сигнал таймера устарел: ход уже сменился. */
    STALE_TIMEOUT,
    /** Сигнал таймера пришёл раньше срока окончания хода. */
    TURN_NOT_EXPIRED,
    /** Голосование уже идёт: новое начать нельзя. */
    VOTE_IN_PROGRESS,
    /** Голосования сейчас нет. */
    NO_VOTE,
    /** Игрок уже проголосовал; изменить голос нельзя. */
    ALREADY_VOTED,
    /** Голосовать могут только игроки со статусом «в игре». */
    NOT_ELIGIBLE_TO_VOTE,
    /** Сигнал о сроке голосования пришёл раньше срока. */
    VOTE_NOT_EXPIRED,
    /** Игрок не участвует в ответах: отсутствовал в момент перехода к ответам. */
    NOT_ANSWER_PARTICIPANT,
    /** Игрок уже отправил ответы. */
    ALREADY_ANSWERED,
    /** Ответы не на все вопросы, на лишние вопросы или с несуществующими вариантами. */
    INVALID_ANSWERS,
    /** Действие доступно только хозяину комнаты. */
    NOT_HOST
}
